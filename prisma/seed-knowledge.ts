export async function seedKnowledge(c: Ctx) {
  const { prisma, now } = c;
  const at = (daysAgo: number) => new Date(now.getTime() - daysAgo * 86400000);
  const mk = async (data: { title: string; body: string; scope: KnowledgeScope; authorId: string; courseId?: string; createdAt: Date; attachmentId?: string }) =>
    prisma.knowledgeDoc.create({ data: { ...data, updatedAt: data.createdAt, chunks: { create: chunkText(data.body).map((x) => ({ idx: x.idx, heading: x.heading, text: x.text })) } } });

  for (const d of DEANERY) await mk({ title: d.title, body: d.body, scope: "UNIVERSITY", authorId: c.staffUserId, createdAt: at(d.daysAgo) });

  // демо-преподаватель: по своей дисциплине (все свои группы)
  const lesson = await prisma.lesson.findFirst({ where: { teacherId: c.demoTeacherId, course: { name: "Алгоритмы и структуры данных" } }, select: { courseId: true } });
  if (!lesson) return DEANERY.length;
  await mk({
    title: "Требования к лабораторным работам",
    scope: "COURSE",
    authorId: c.teacherUserId,
    courseId: lesson.courseId,
    createdAt: at(1),
    body: `Оформление отчёта
Отчёт оформляется по шаблону из материалов курса: титульный лист, цель работы, описание алгоритма, код с комментариями, таблица замеров времени и выводы. Формат — Word или PDF.

Сроки и опоздания
Работа сдаётся до 23:59 дня срока. За каждую неделю опоздания максимальный балл снижается на 2. Через три недели после срока работа не принимается без уважительной причины.

Доработка
Если работу вернули на доработку, исправленный вариант нужно отправить в течение недели. Баллы за доработанную работу не снижаются.

Баллы
Каждая лабораторная — до 10 баллов. Для допуска к экзамену нужно сдать все лабораторные и набрать не меньше 50 баллов за семестр.`,
  });
  await mk({
    title: "Вопросы к экзамену",
    scope: "COURSE",
    authorId: c.teacherUserId,
    courseId: lesson.courseId,
    createdAt: at(6),
    body: `Формат экзамена
Экзамен устный, по билетам. В билете два теоретических вопроса и одна задача. На подготовку — 40 минут. Пользоваться конспектом нельзя.

Теоретические вопросы
1. Асимптотическая сложность, O-нотация. 2. Массивы и связные списки. 3. Стек и очередь. 4. Хеш-таблицы, разрешение коллизий. 5. Двоичные деревья поиска. 6. Сбалансированные деревья (AVL, красно-чёрные). 7. Куча и пирамидальная сортировка. 8. Быстрая сортировка и сортировка слиянием. 9. Графы: обход в ширину и в глубину. 10. Кратчайшие пути, алгоритм Дейкстры.

Автомат
Студенты, набравшие за семестр 85 баллов и больше, могут получить «отлично» автоматом без сдачи экзамена.`,
  });

  // материал, загруженный из файла Word — как при загрузке через сайт (текст извлечён автоматически)
  const fixture = path.join(__dirname, "fixtures", "lab5-task.docx");
  const buf = await fs.readFile(fixture);
  const body = await extractText("lab5-task.docx", buf);
  const storageKey = randomBytes(18).toString("hex");
  const dir = path.join(process.env.DATA_DIR || "./data", "uploads");
  await fs.mkdir(dir, { recursive: true });
  await fs.writeFile(path.join(dir, storageKey), buf);
  const att = await prisma.attachment.create({ data: { name: "Условие лабораторной №5.docx", mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document", size: buf.length, storageKey, uploadedById: c.teacherUserId } });
  await mk({ title: "Лабораторная №5: условие и критерии", body, scope: "COURSE", authorId: c.teacherUserId, courseId: lesson.courseId, createdAt: at(3), attachmentId: att.id });
  return DEANERY.length + 3;
}
